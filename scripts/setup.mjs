import { spawnSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { readFileSync, writeFileSync, chmodSync } from 'node:fs'
import { parseEnv } from 'node:util'

const localDatabase = 'postgresql://taakra:taakra-local@127.0.0.1:5432/taakra'

function run(command, args, errorMessage, env) {
  const result = spawnSync(command, args, { stdio: 'inherit', env })
  if (result.signal === 'SIGINT' || result.status === 130) process.exit(130)
  if (result.signal === 'SIGTERM' || result.status === 143) process.exit(143)
  if (result.error || result.status !== 0) throw new Error(errorMessage)
}

function developmentEnvironment() {
  let contents
  try {
    contents = readFileSync('.env', 'utf8')
  } catch (error) {
    if (error.code !== 'ENOENT') throw new Error('Could not read the local .env file.')
  }
  const fromFile = contents === undefined ? {} : parseEnv(contents)
  const configured = { ...fromFile, ...process.env }
  if (configured.NODE_ENV === 'production') {
    throw new Error('For production, configure the server environment and use npm run start:deploy after building.')
  }

  const defaults = {}
  if (!configured.APP_SECRET) defaults.APP_SECRET = fromFile.APP_SECRET || randomBytes(32).toString('hex')
  if (!configured.DATABASE_URL) defaults.DATABASE_URL = fromFile.DATABASE_URL || localDatabase
  if (!configured.RETENTION_DAYS) defaults.RETENTION_DAYS = fromFile.RETENTION_DAYS || '7'
  const additions = Object.entries(defaults).filter(([key]) => !fromFile[key])
  if (additions.length) {
    const lines = additions.map(([key, value]) => `${key}=${value}`)
    const block = `# Local development settings generated by npm run setup.\n${lines.join('\n')}\n`
    try {
      if (contents === undefined) {
        writeFileSync('.env', block, { flag: 'wx', mode: 0o600 })
      } else {
        chmodSync('.env', 0o600)
        writeFileSync('.env', `\n${block}`, { flag: 'a' })
      }
    } catch {
      throw new Error('Could not save the generated local .env settings.')
    }
    console.log('Saved missing local development settings in .env.')
  }

  return { ...configured, ...defaults }
}

function main() {
  const npm = [process.execPath, process.env.npm_execpath]
  if (!npm[1]) throw new Error('Run this script with npm run setup.')
  const settings = developmentEnvironment()
  // Preserve the normal precedence of exported variables over .env and supply generated defaults.
  const env = { ...process.env, APP_SECRET: settings.APP_SECRET, DATABASE_URL: settings.DATABASE_URL, RETENTION_DAYS: settings.RETENTION_DAYS }
  if (settings.DATABASE_URL === localDatabase) {
    console.log('Starting the local PostgreSQL database…')
    run('docker', ['compose', '--progress', 'plain', 'up', '-d', '--wait', '--wait-timeout', '60', 'db'],
      'Could not start PostgreSQL. Check that Docker is running and port 5432 is available.', env)
  }

  run(npm[0], [npm[1], 'ci', '--include=dev', '--prefer-offline', '--cache', '.cache/npm'],
    'Dependency installation failed.', env)
  run(npm[0], [npm[1], 'run', 'db:migrate'], 'Database migration failed.', env)
  console.log('Starting the API and frontend…')
  run(npm[0], [npm[1], 'run', 'dev'], 'The development server stopped with an error.', env)
}

try {
  main()
} catch (error) {
  console.error(error.message)
  process.exitCode = 1
}
